from abc import ABC, abstractmethod
from datetime import datetime
from typing import Protocol
from alarm_clock.models import Alarm

class Clock(Protocol):
    def now(self) -> datetime: ...

class AlarmRepository(Protocol):
    def add(self, alarm: Alarm) -> Alarm: ...
    def get(self, alarm_id: int) -> Alarm: ...
    def list_all(self) -> list[Alarm]: ...
    def delete(self, alarm_id: int) -> None: ...

class Notifier(ABC):
    @abstractmethod
    def notify(self, alarm: Alarm) -> None: ...

    @abstractmethod
    def wait_for_dismissal(self) -> None: ...
